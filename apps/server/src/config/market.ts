/**
 * パーツ相場の係数（CLAUDE.md「パーツ相場」）
 *
 * 相場倍率 = （購入率 ÷ 全パーツの平均購入率）^exponent を、前週の倍率と移動平均し、上下限で抑える。
 * 更新は週1回（年52回）。1回あたりのデータは日次の約7倍になるので、反応を少し速め、閾値を上げている。
 * 調整するときはここだけを変える。
 */
export const MARKET_CONFIG = {
  /** 購入率の比に掛ける指数 k（1未満にすると動きがゆるやかになる） */
  exponent: 0.5,
  /** 移動平均で「新しい値」に掛ける重み（0〜1。残りは前週の倍率） */
  smoothing: 0.7,
  /** 倍率の下限・上限 */
  minMultiplier: 0.5,
  maxMultiplier: 2.0,
  /** 前週の参加人数がこれ未満なら据え置き（過疎期に相場が暴れないように） */
  minPlayers: 50,
  /** このパーツの前週の出現数がこれ未満なら、そのパーツは据え置き（1回の偶然で動かないように） */
  minOffered: 100,
} as const;
